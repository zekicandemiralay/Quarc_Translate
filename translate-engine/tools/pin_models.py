"""Regenerates model_pins.py: for every dedicated pair the engine offers, the
exact Hugging Face commit to download. Run it when you add a pair or want to
move to newer model revisions, then re-test:

    python tools/pin_models.py > model_pins.py

Standard library only. Needs network access to huggingface.co.
"""

import json
import sys
import urllib.request

# language → (repo suffix for en→language, repo suffix for language→en); None = no dedicated model
# in that direction, NLLB handles it. "tc-big-…" = transformer-big (~280 MB RAM), the rest
# transformer-base (~110 MB).
#
# Only directions that passed the round-trip check against NLLB-1.3B are listed (README, "Model
# quality"): 8 test sentences per language; a dedicated model is used when translating through it
# scores within 2 chrF points of NLLB's own round trip (and, for English→X, agrees with NLLB ≥ 75).
# It is a regression guard, not a benchmark. Measured and REJECTED — NLLB serves these better:
# ru, zh, ja, ko (tc-big-en-ko is unusable without a target tag), hi, vi, uk, ro, az, ur, and the
# other direction of ar/nl/pl/sv/da/ca/et/lv/lt/sq/is.
PAIRS = {
    "tr": ("tc-big-en-tr", "tc-big-tr-en"),
    "de": ("en-de", "de-en"),
    "fr": ("tc-big-en-fr", "tc-big-fr-en"),
    "es": ("tc-big-en-es", "es-en"),
    "it": ("tc-big-en-it", "tc-big-it-en"),
    "pt": ("tc-big-en-pt", None),
    "ar": ("tc-big-en-ar", None),
    "nl": ("en-nl", None),
    "pl": (None, "pl-en"),
    "sv": (None, "sv-en"),
    "el": ("tc-big-en-el", "tc-big-el-en"),
    "id": ("en-id", "id-en"),
    "cs": ("en-cs", "cs-en"),
    "fi": ("tc-big-en-fi", "tc-big-fi-en"),
    "da": (None, "da-en"),
    "hu": ("tc-big-en-hu", "tc-big-hu-en"),
    "sk": ("en-sk", "sk-en"),
    "he": ("en-he", "tc-big-he-en"),
    "th": (None, "th-en"),
    "ca": ("en-ca", None),
    "et": (None, "tc-big-et-en"),
    "lv": (None, "tc-big-lv-en"),
    "lt": ("tc-big-en-lt", None),
    "sq": ("en-sq", None),
    "is": (None, "is-en"),
}

NLLB_REPOS = [
    "OpenNMT/nllb-200-distilled-1.3B-ct2-int8",
    "JustFrederik/nllb-200-distilled-600M-ct2-int8",
    "facebook/nllb-200-distilled-600M",
]


def sha(repo):
    with urllib.request.urlopen(f"https://huggingface.co/api/models/{repo}", timeout=30) as r:
        return json.load(r)["sha"]


def main():
    print('"""Generated by tools/pin_models.py — do not edit by hand."""\n')
    print("# (source, target) -> (repo suffix after Helsinki-NLP/opus-mt-, pinned revision, approx RAM in MB)")
    print("DEDICATED = {")
    for lang, (to_lang, from_lang) in PAIRS.items():
        for pair, suffix in ((("en", lang), to_lang), ((lang, "en"), from_lang)):
            if not suffix:
                continue
            size = 280 if suffix.startswith("tc-big") else 110
            print(f'    {pair!r}: ("{suffix}", "{sha("Helsinki-NLP/opus-mt-" + suffix)}", {size}),')
    print("}\n")
    print("# Revisions of the general model and its tokenizer.")
    print("NLLB_REVISIONS = {")
    for repo in NLLB_REPOS:
        print(f'    "{repo}": "{sha(repo)}",')
    print("}")


if __name__ == "__main__":
    sys.exit(main())
