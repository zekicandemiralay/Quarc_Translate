"""Which model translates which pair.

Measured on the real models (see the engine README): a *dedicated* model — one
trained for exactly one language pair — matches or beats NLLB-1.3B on the pairs
below while being ~10× faster and needing a fifth of the RAM. So:

  1. a dedicated model for the exact pair, if there is one;
  2. else, if both halves exist, translate through English with two dedicated
     models (de→tr = de→en→tr: as good as NLLB's direct route, and quicker);
  3. else NLLB-200 (1.3B by default), which knows ~200 languages.

Everything is pinned to a Hugging Face revision, so what runs is exactly what
was tested, no matter what is pushed to those repositories later.
"""

from dataclasses import dataclass

import config
import languages


@dataclass(frozen=True)
class ModelSpec:
    key: str  # folder name under MODEL_DIR/ct2 and the id shown in the app
    kind: str  # "marian" (one pair) | "nllb" (general)
    repo: str  # Hugging Face repository
    revision: str  # pinned commit
    obtain: str  # "convert": download the original, convert to CTranslate2 int8 | "prebuilt": download CTranslate2 files
    size_mb: int  # about what it occupies in RAM (and on disk)
    tokenizer_repo: str = ""  # NLLB only: where its tokenizer files come from
    tokenizer_revision: str = ""
    label: str = ""


@dataclass(frozen=True)
class Step:
    model: ModelSpec
    source: str
    target: str


# Generated by tools/pin_models.py from the Hugging Face API:
#   DEDICATED      {(source, target): (repo suffix, revision, MB in RAM)}
#   NLLB_REVISIONS {repo: revision}
# "tc-big" = transformer-big (higher quality, ~280 MB RAM), the rest transformer-base (~110 MB).
from model_pins import DEDICATED, NLLB_REVISIONS  # noqa: E402

_TOKENIZER_REPO = "facebook/nllb-200-distilled-600M"


def _nllb(key, repo, size_mb, label):
    return ModelSpec(
        key=key,
        kind="nllb",
        repo=repo,
        revision=NLLB_REVISIONS[repo],
        obtain="prebuilt",
        size_mb=size_mb,
        tokenizer_repo=_TOKENIZER_REPO,
        tokenizer_revision=NLLB_REVISIONS[_TOKENIZER_REPO],
        label=label,
    )


NLLB_MODELS = {
    "1.3B": _nllb("nllb-200-distilled-1.3B", "OpenNMT/nllb-200-distilled-1.3B-ct2-int8", 1500, "NLLB-200 1.3B"),
    "600M": _nllb("nllb-200-distilled-600M", "JustFrederik/nllb-200-distilled-600M-ct2-int8", 760, "NLLB-200 600M"),
}


def _dedicated_spec(source, target):
    entry = DEDICATED.get((source, target))
    if not entry:
        return None
    suffix, revision, size = entry
    return ModelSpec(
        key=f"opus-mt-{suffix}",
        kind="marian",
        repo=f"Helsinki-NLP/opus-mt-{suffix}",
        revision=revision,
        obtain="convert",
        size_mb=size,
        label=f"OPUS-MT {suffix}",
    )


def general_model():
    return NLLB_MODELS.get(config.NLLB_SIZE, NLLB_MODELS["1.3B"])


def all_specs():
    """Every model this engine could ever load (for the status page)."""
    seen = {}
    for pair in DEDICATED:
        spec = _dedicated_spec(*pair)
        seen[spec.key] = spec
    for spec in NLLB_MODELS.values():
        seen[spec.key] = spec
    return seen


def plan(source, target):
    """Steps that turn `source` text into `target` text (already-validated registry codes)."""
    direct = _dedicated_spec(source, target)
    if direct:
        return [Step(direct, source, target)]

    if config.PIVOT == "auto" and "en" not in (source, target):
        first, second = _dedicated_spec(source, "en"), _dedicated_spec("en", target)
        if first and second:
            return [Step(first, source, "en"), Step(second, "en", target)]

    return [Step(general_model(), source, target)]


def pair_label(source, target):
    return f"{source}-{target}"


def routes_summary():
    """For the status endpoint: how each language is served when translating to/from English."""
    out = {}
    for code in languages.LANGUAGES:
        if code == "en":
            continue
        out[code] = {
            "toEnglish": "dedicated" if _dedicated_spec(code, "en") else "general",
            "fromEnglish": "dedicated" if _dedicated_spec("en", code) else "general",
        }
    return out
